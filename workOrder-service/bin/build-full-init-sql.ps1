param(
    [string]$OutputPath = ""
)

$ErrorActionPreference = "Stop"

# Keep the generated bundle deterministic. Add every new schema or seed fragment
# to this manifest in dependency order, then regenerate the bundle.
$scriptRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$serviceRoot = Split-Path -Parent $scriptRoot
$sqlRoot = Join-Path $serviceRoot "sql"
$sourceFiles = @(
    "ry_20250522.sql",
    "quartz.sql",
    "03_workorder_core_schema.sql",
    "04_workorder_dict.sql",
    "05_workorder_menu.sql",
    "06_workorder_role_grant.sql",
    "07_workorder_seed.sql",
    "08_workorder_m1_core_adjust.sql",
    "09_workorder_m1_b02.sql",
    "10_workorder_m1_d03.sql",
    "11_workorder_f01_sla_delay.sql",
    "12_workorder_f02_notification.sql",
    "13_workorder_f04_operations.sql",
    "14_workorder_integration_seed.sql",
    "15_workorder_dept_selector_permission.sql"
)

if ([string]::IsNullOrWhiteSpace($OutputPath)) {
    $OutputPath = Join-Path $sqlRoot "00_workorder_full_init.sql"
} elseif (-not [System.IO.Path]::IsPathRooted($OutputPath)) {
    $OutputPath = Join-Path $serviceRoot $OutputPath
}

$utf8WithoutBom = New-Object System.Text.UTF8Encoding($false)
$builder = New-Object System.Text.StringBuilder

[void]$builder.AppendLine("-- Work Order complete database initialization for MySQL 8.0")
[void]$builder.AppendLine("-- GENERATED FILE: do not edit this file directly.")
[void]$builder.AppendLine("-- Run bin/build-full-init-sql.ps1 after changing a source SQL fragment.")
[void]$builder.AppendLine("-- WARNING: the base RuoYi and Quartz fragments drop and recreate system tables.")
[void]$builder.AppendLine("-- Use this bundle only for a new local, integration, or regression database.")
[void]$builder.AppendLine("-- The integration accounts use the local-only initial password documented in the project manual.")
[void]$builder.AppendLine("")
[void]$builder.AppendLine("SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci;")
[void]$builder.AppendLine("SET time_zone = '+08:00';")
[void]$builder.AppendLine("SET FOREIGN_KEY_CHECKS = 0;")
[void]$builder.AppendLine("CREATE DATABASE IF NOT EXISTS ``workorder`` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;")
[void]$builder.AppendLine("USE ``workorder``;")
[void]$builder.AppendLine("")

foreach ($sourceFile in $sourceFiles) {
    $sourcePath = Join-Path $sqlRoot $sourceFile
    if (-not (Test-Path -LiteralPath $sourcePath -PathType Leaf)) {
        throw "Required SQL source file is missing: $sourcePath"
    }

    $content = [System.IO.File]::ReadAllText($sourcePath, $utf8WithoutBom)
    $hash = (Get-FileHash -LiteralPath $sourcePath -Algorithm SHA256).Hash.ToLowerInvariant()

    [void]$builder.AppendLine("-- ============================================================================")
    [void]$builder.AppendLine("-- BEGIN SOURCE: $sourceFile")
    [void]$builder.AppendLine("-- SHA256: $hash")
    [void]$builder.AppendLine("-- ============================================================================")
    [void]$builder.AppendLine($content.TrimEnd())
    [void]$builder.AppendLine("-- END SOURCE: $sourceFile")
    [void]$builder.AppendLine("")
}

[void]$builder.AppendLine("SET FOREIGN_KEY_CHECKS = 1;")
[void]$builder.AppendLine("")
[void]$builder.AppendLine("-- Final initialization summary. Review each count before starting integration tests.")
[void]$builder.AppendLine("SELECT DATABASE() AS database_name;")
[void]$builder.AppendLine("SELECT COUNT(*) AS workorder_table_count")
[void]$builder.AppendLine("FROM information_schema.tables")
[void]$builder.AppendLine("WHERE table_schema = DATABASE() AND table_name LIKE 'wo\_%' ESCAPE '\\';")
[void]$builder.AppendLine("SELECT COUNT(*) AS enabled_category_count FROM wo_category WHERE enabled = 1 AND deleted = 0;")
[void]$builder.AppendLine("SELECT COUNT(*) AS workorder_role_count FROM sys_role WHERE role_key LIKE 'workorder\_%' ESCAPE '\\' AND del_flag = '0';")
[void]$builder.AppendLine("SELECT COUNT(*) AS integration_user_count FROM sys_user WHERE user_name IN ('wo_reporter', 'wo_engineer', 'wo_dispatcher') AND del_flag = '0';")
[void]$builder.AppendLine("SELECT COUNT(*) AS enabled_notification_template_count FROM wo_notification_template WHERE enabled = 1 AND deleted = 0;")
[void]$builder.AppendLine("SELECT COUNT(*) AS enabled_workorder_job_count FROM sys_job WHERE job_group = 'WORKORDER' AND status = '0';")

$outputDirectory = Split-Path -Parent $OutputPath
if (-not (Test-Path -LiteralPath $outputDirectory -PathType Container)) {
    New-Item -ItemType Directory -Path $outputDirectory | Out-Null
}

[System.IO.File]::WriteAllText($OutputPath, $builder.ToString(), $utf8WithoutBom)
Write-Host "Generated complete SQL bundle: $OutputPath"
